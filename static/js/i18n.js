class I18nManager {
    constructor() {
        this.currentLang = localStorage.getItem('smartaid_lang') || 'en';
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', () => this.init());
        } else {
            this.init();
        }
    }

    init() {
        this.applyTranslations();
        this.renderLanguagePill();
    }

    getLang() {
        return this.currentLang;
    }

    t(key) {
        const dict = SmartAidTranslations[this.currentLang] || SmartAidTranslations.en;
        return dict[key] || SmartAidTranslations.en[key] || key;
    }

    setLanguage(lang) {
        if (!SmartAidTranslations[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('smartaid_lang', lang);
        this.applyTranslations();
        this.renderLanguagePill();
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }

    toggleLanguage() {
        this.setLanguage(this.currentLang === 'en' ? 'ceb' : 'en');
    }

    applyTranslations() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (translation) {
                const icon = el.querySelector('i[data-lucide]');
                if (icon) {
                    const iconHTML = icon.outerHTML;
                    el.innerHTML = iconHTML + ' <span>' + translation + '</span>';
                } else {
                    el.textContent = translation;
                }
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = this.t(key);
            if (translation) {
                el.placeholder = translation;
            }
        });

        document.documentElement.lang = this.currentLang === 'ceb' ? 'ceb' : 'en';
    }

    renderLanguagePill() {
        const containers = document.querySelectorAll('.lang-switcher-mount');
        const isCeb = this.currentLang === 'ceb';
        
        containers.forEach(mount => {
            const label = isCeb ? '🇵🇭 Bisaya' : '🇺🇸 English';
            const btnClass = isCeb 
                ? 'bg-amber-500/10 text-amber-700 border-amber-500/30 hover:bg-amber-500/20' 
                : 'bg-indigo-500/10 text-indigo-700 border-indigo-500/30 hover:bg-indigo-500/20';
            mount.innerHTML = `<button type="button" onclick="window.i18n.toggleLanguage()" class="btn-press inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-semibold transition-all border shadow-2xs ${btnClass}"><span>${label}</span><span class="text-[10px] text-slate-400">⇄</span></button>`;
        });
    }
}

window.i18n = new I18nManager();
